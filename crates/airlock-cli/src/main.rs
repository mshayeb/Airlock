//! Airlock CLI (`clig.dev`, `WCAG 2.2 AA`, and `spec.md` §10–§11 compliant).

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

use airlock_vmm::AppleVzBackend;
use airlockd::audit::AuditLog;

const EXIT_OK: u8 = 0;
const EXIT_INFRA: u8 = 70;
const EXIT_CONFIG: u8 = 78;
const EXIT_REJECTED: u8 = 79;

struct UiStyle {
    color: bool,
    plain: bool,
    json: bool,
}

impl UiStyle {
    fn detect(json: bool, plain: bool) -> Self {
        let no_color = env::var_os("NO_COLOR").is_some()
            || env::var("CLICOLOR").ok().as_deref() == Some("0")
            || env::var("TERM").ok().as_deref() == Some("dumb");
        Self {
            color: !no_color && !json && !plain,
            plain,
            json,
        }
    }

    fn badge(&self, tag: &str) -> String {
        if !self.color {
            return format!("[{tag}]");
        }
        // WCAG 2.2 AA high-contrast ANSI foreground codes paired with explicit text labels.
        let code = match tag {
            "SEALED" | "ALLOW" => "32;1",
            "REVIEW" => "33;1",
            "BLOCKED" => "31;1",
            _ => "36;1",
        };
        format!("\x1b[{code}m[{tag}]\x1b[0m")
    }
}

#[derive(Debug)]
struct DoctorCheck {
    name: &'static str,
    status: &'static str,
    detail: String,
}

fn main() -> ExitCode {
    let args: Vec<String> = env::args().skip(1).collect();
    if args.is_empty() || args.iter().any(|a| a == "-h" || a == "--help") {
        print_help();
        return ExitCode::from(EXIT_OK);
    }

    let json = args.iter().any(|a| a == "--json");
    let plain = args.iter().any(|a| a == "--plain");
    let ui = UiStyle::detect(json, plain);

    let sub = args[0].as_str();
    let rest: Vec<&str> = args[1..]
        .iter()
        .map(String::as_str)
        .filter(|a| *a != "--json" && *a != "--plain")
        .collect();

    let code = match sub {
        "version" | "--version" | "-V" => cmd_version(&ui),
        "init" => cmd_init(&ui, &rest),
        "doctor" => cmd_doctor(&ui),
        "logs" => cmd_logs(&ui, &rest),
        other => {
            eprintln!(
                "{} Unknown command `{other}`. Run `airlock --help` for usage.",
                ui.badge("BLOCKED")
            );
            EXIT_CONFIG
        }
    };

    ExitCode::from(code)
}

fn print_help() {
    println!(
        "airlock {} — Secretless microVM Chambers for AI Agents\n\n\
         USAGE:\n  airlock <COMMAND> [OPTIONS]\n\n\
         COMMANDS:\n  \
           init [dir]              Generate a least-privilege airlock.toml (version = \"1\")\n  \
           doctor                  Verify host hypervisor, APFS/EROFS, and path readiness\n  \
           logs --verify <file>    Verify SHA-256 hash-chain integrity of audit.jsonl\n  \
           version                 Print Airlock version and Phase 1 spec alignment\n\n\
         GLOBAL FLAGS:\n  \
           --json                  Emit structured JSON to stdout\n  \
           --plain                 Emit linear screen-reader-friendly plain text\n  \
           -h, --help              Show this help",
        env!("CARGO_PKG_VERSION")
    );
}

fn cmd_version(ui: &UiStyle) -> u8 {
    let ver = env!("CARGO_PKG_VERSION");
    if ui.json {
        println!(
            "{{\"name\":\"airlock\",\"version\":\"{ver}\",\"spec_version\":\"1.0\",\"phase\":1}}"
        );
    } else {
        println!("airlock {ver} (Phase 1 · Spec v1.0)");
    }
    EXIT_OK
}

fn cmd_init(ui: &UiStyle, rest: &[&str]) -> u8 {
    let force = rest.contains(&"--force");
    let dir = rest
        .iter()
        .copied()
        .find(|a| !a.starts_with('-'))
        .map(PathBuf::from)
        .unwrap_or_else(|| env::current_dir().unwrap_or_else(|_| PathBuf::from(".")));

    let out_path = dir.join("airlock.toml");
    if out_path.exists() && !force {
        eprintln!(
            "{} {} already exists. Pass --force to overwrite.",
            ui.badge("REVIEW"),
            out_path.display()
        );
        return EXIT_CONFIG;
    }

    let has_cargo = dir.join("Cargo.toml").exists();
    let has_node = dir.join("package.json").exists();
    let has_py = dir.join("pyproject.toml").exists() || dir.join("requirements.txt").exists();

    let mut hosts = Vec::new();
    if has_node {
        hosts.push("\"registry.npmjs.org\"");
    }
    if has_py {
        hosts.extend_from_slice(&["\"pypi.org\"", "\"files.pythonhosted.org\""]);
    }
    if has_cargo {
        hosts.extend_from_slice(&["\"crates.io\"", "\"static.crates.io\""]);
    }
    if hosts.is_empty() {
        hosts.extend_from_slice(&["\"pypi.org\"", "\"registry.npmjs.org\""]);
    }

    let manifest = format!(
        concat!(
            "# Generated by `airlock init` (Phase 1 · Spec v1.0)\n",
            "version = \"1\"\n\n",
            "[chamber]\n",
            "target = \"local\"\n",
            "profile = \"standard\"\n",
            "vcpus = 2\n",
            "memory_mib = 4096\n",
            "disk_upper_mib = 8192\n",
            "ttl_seconds = 3600\n\n",
            "[workspace]\n",
            "synthesize_env_from_example = true\n",
            "protected_paths = [\".git/**\", \".github/workflows/**\", \"airlock.toml\", \"Dockerfile\", \"Makefile\"]\n\n",
            "[[capabilities]]\n",
            "id = \"pkg_registries\"\n",
            "type = \"http\"\n",
            "provider = \"none\"\n",
            "hosts = [{hosts}]\n",
            "allow_methods = [\"GET\", \"HEAD\"]\n",
            "strip_query_params = true\n",
            "tls_mode = \"terminate\"\n\n",
            "[commit_gate]\n",
            "mode = \"interactive\"\n",
            "secret_scan = \"block\"\n",
            "max_diff_mib = 50\n\n",
            "[audit]\n",
            "hash_chain = true\n",
            "capture_http_bodies = false\n"
        ),
        hosts = hosts.join(", "),
    );

    if let Err(err) = fs::write(&out_path, manifest) {
        eprintln!(
            "{} Failed to write {}: {err}",
            ui.badge("BLOCKED"),
            out_path.display()
        );
        return EXIT_INFRA;
    }

    if ui.json {
        println!(
            "{{\"status\":\"SEALED\",\"path\":\"{}\"}}",
            escape_json(&out_path.to_string_lossy())
        );
    } else {
        println!(
            "{} Created least-privilege manifest at {}",
            ui.badge("ALLOW"),
            out_path.display()
        );
    }
    EXIT_OK
}

fn cmd_doctor(ui: &UiStyle) -> u8 {
    let mut checks = Vec::new();
    let mut infra_ok = true;

    let cwd = env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    let cwd_str = cwd.to_string_lossy();
    if cwd_str.ends_with(' ') {
        checks.push(DoctorCheck {
            name: "workspace_path_hygiene",
            status: "REVIEW",
            detail: format!(
                "Workspace path `{cwd_str}` ends with trailing whitespace (`C9`/`D-10`); rename recommended."
            ),
        });
    } else {
        checks.push(DoctorCheck {
            name: "workspace_path_hygiene",
            status: "ALLOW",
            detail: format!("Clean workspace path: {cwd_str}"),
        });
    }

    if cfg!(target_os = "macos") {
        let arch = env::consts::ARCH;
        if arch != "aarch64" {
            infra_ok = false;
            checks.push(DoctorCheck {
                name: "macos_apple_silicon",
                status: "BLOCKED",
                detail: format!("Apple Silicon (aarch64) required; detected {arch}"),
            });
        } else {
            checks.push(DoctorCheck {
                name: "macos_apple_silicon",
                status: "ALLOW",
                detail: "Apple Silicon (aarch64) host detected".to_owned(),
            });
        }

        let helper = find_vz_helper(&cwd);
        match helper {
            Some(path) => match AppleVzBackend::probe(&path) {
                Ok(raw) => checks.push(DoctorCheck {
                    name: "apple_vz_helper",
                    status: "SEALED",
                    detail: format!("{} -> {raw}", path.display()),
                }),
                Err(err) => {
                    checks.push(DoctorCheck {
                        name: "apple_vz_helper",
                        status: "REVIEW",
                        detail: format!(
                            "Helper present at {} but probe returned: {err}",
                            path.display()
                        ),
                    });
                }
            },
            None => checks.push(DoctorCheck {
                name: "apple_vz_helper",
                status: "REVIEW",
                detail: "airlock-vz-helper not built yet; run `macos/airlock-vz-helper/build.sh`"
                    .to_owned(),
            }),
        }
    } else if cfg!(target_os = "linux") {
        let kvm_path = Path::new("/dev/kvm");
        let (kvm_status, kvm_detail) = if !kvm_path.exists() {
            infra_ok = false;
            (
                "BLOCKED",
                "/dev/kvm missing; KVM required for Firecracker".to_owned(),
            )
        } else {
            match fs::OpenOptions::new().read(true).write(true).open(kvm_path) {
                Ok(_) => (
                    "ALLOW",
                    "/dev/kvm present and read/write accessible".to_owned(),
                ),
                Err(err) => {
                    infra_ok = false;
                    (
                        "BLOCKED",
                        format!(
                            "/dev/kvm permission denied ({err}); grant runner user access to kvm group"
                        ),
                    )
                }
            }
        };
        checks.push(DoctorCheck {
            name: "linux_kvm",
            status: kvm_status,
            detail: kvm_detail,
        });
        for bin in ["firecracker", "jailer", "mkfs.erofs"] {
            let found = Command::new("which").arg(bin).output().is_ok_and(|o| o.status.success());
            checks.push(DoctorCheck {
                name: bin,
                status: if found { "ALLOW" } else { "REVIEW" },
                detail: if found {
                    format!("{bin} found in PATH")
                } else {
                    format!("{bin} not installed in PATH")
                },
            });
        }
    }

    if ui.json {
        let items: Vec<String> = checks
            .iter()
            .map(|c| {
                format!(
                    "{{\"check\":\"{}\",\"status\":\"{}\",\"detail\":\"{}\"}}",
                    c.name,
                    c.status,
                    escape_json(&c.detail)
                )
            })
            .collect();
        println!(
            "{{\"os\":\"{}\",\"arch\":\"{}\",\"checks\":[{}]}}",
            env::consts::OS,
            env::consts::ARCH,
            items.join(",")
        );
    } else if ui.plain {
        println!("Airlock Doctor ({}/{})", env::consts::OS, env::consts::ARCH);
        for c in &checks {
            println!("[{}] {}: {}", c.status, c.name, c.detail);
        }
    } else {
        println!(
            "{} Airlock Host Check ({}/{})",
            ui.badge("SEALED"),
            env::consts::OS,
            env::consts::ARCH
        );
        for c in &checks {
            println!("  {} {}: {}", ui.badge(c.status), c.name, c.detail);
        }
    }

    if infra_ok { EXIT_OK } else { EXIT_INFRA }
}

fn find_vz_helper(cwd: &Path) -> Option<PathBuf> {
    let candidate = cwd.join("macos/airlock-vz-helper/bin/airlock-vz-helper");
    if candidate.is_file() {
        return Some(candidate);
    }
    None
}

fn cmd_logs(ui: &UiStyle, rest: &[&str]) -> u8 {
    let verify = rest.contains(&"--verify");
    let path = rest.iter().copied().find(|a| !a.starts_with('-'));
    let Some(file_path) = path else {
        eprintln!(
            "{} Usage: airlock logs --verify <audit.jsonl>",
            ui.badge("BLOCKED")
        );
        return EXIT_CONFIG;
    };

    if !verify {
        match fs::read_to_string(file_path) {
            Ok(raw) => {
                print!("{raw}");
                return EXIT_OK;
            }
            Err(err) => {
                eprintln!("{} Failed to read {file_path}: {err}", ui.badge("BLOCKED"));
                return EXIT_INFRA;
            }
        }
    }

    match AuditLog::verify_file(Path::new(file_path)) {
        Ok(count) => {
            if ui.json {
                println!(
                    "{{\"status\":\"SEALED\",\"verified_events\":{count},\"file\":\"{}\"}}",
                    escape_json(file_path)
                );
            } else {
                println!(
                    "{} Hash chain verified ({count} events) in {file_path}",
                    ui.badge("SEALED")
                );
            }
            EXIT_OK
        }
        Err(err) => {
            if ui.json {
                println!(
                    "{{\"status\":\"BLOCKED\",\"error\":\"{}\"}}",
                    escape_json(&err.to_string())
                );
            } else {
                eprintln!("{} {err}", ui.badge("BLOCKED"));
            }
            EXIT_REJECTED
        }
    }
}

fn escape_json(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}
